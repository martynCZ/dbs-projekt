-- Evidence licencí a plateb softwaru pro školy
-- Vytvoří schéma licence a v něm 8 tabulek.

CREATE SCHEMA IF NOT EXISTS licence;
SET search_path TO licence;


-- Smazání tabulek, pokud už existují (v opačném pořadí, než se vytváří)
DROP TABLE IF EXISTS pohyby;
DROP TABLE IF EXISTS platby;
DROP TABLE IF EXISTS faktury;
DROP TABLE IF EXISTS zakaznik_zaznamy;
DROP TABLE IF EXISTS aktivace;
DROP TABLE IF EXISTS verze_programu;
DROP TABLE IF EXISTS licence;
DROP TABLE IF EXISTS zakaznici;


-- Zákazníci (školy)
CREATE TABLE zakaznici (
    zakaznik_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazev         VARCHAR(200) NOT NULL,
    ico           CHAR(8) UNIQUE,
    adresa        VARCHAR(200),
    email         VARCHAR(150) NOT NULL,
    kontakt       VARCHAR(100),
    telefon       VARCHAR(20),
    stav          VARCHAR(10) NOT NULL DEFAULT 'zajemce',
    ozvat_se      DATE,
    vytvoreno     DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT ck_zakaznici_stav CHECK (stav IN ('zajemce', 'zkousi', 'plati', 'odesla'))
);

-- Licence (jedna licence = jedna instalace programu)
CREATE TABLE licence (
    licence_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zakaznik_id   INTEGER NOT NULL,
    kod           CHAR(19) NOT NULL UNIQUE,
    popisek       VARCHAR(100),
    edice         VARCHAR(10) NOT NULL DEFAULT 'pro',
    max_stanic    INTEGER NOT NULL DEFAULT 30,
    plati_do      DATE NOT NULL,
    zruseno       BOOLEAN NOT NULL DEFAULT FALSE,
    archivovano   DATE,
    vytvoreno     DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT fk_licence_zakaznik FOREIGN KEY (zakaznik_id) REFERENCES zakaznici(zakaznik_id),
    CONSTRAINT ck_licence_edice CHECK (edice IN ('pro', 'basic', 'trial')),
    CONSTRAINT ck_licence_max_stanic CHECK (max_stanic > 0)
);

-- Vydané verze programu (klíčem je číslo verze)
CREATE TABLE verze_programu (
    verze         VARCHAR(11) PRIMARY KEY,
    odkaz         VARCHAR(500) NOT NULL,
    poznamky      TEXT,
    vydano        DATE NOT NULL DEFAULT CURRENT_DATE
);

-- Aktivace (počítač, na kterém je licence aktivovaná)
CREATE TABLE aktivace (
    aktivace_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    licence_id        INTEGER NOT NULL,
    machine_id        VARCHAR(32) NOT NULL,
    poradi            INTEGER NOT NULL,
    prvni_vydani      DATE NOT NULL DEFAULT CURRENT_DATE,
    posledni          DATE NOT NULL DEFAULT CURRENT_DATE,
    vyrazeno          DATE,
    hlaseno           DATE,
    verze_konzole     VARCHAR(11),
    hlasenych_stanic  INTEGER,
    CONSTRAINT fk_aktivace_licence FOREIGN KEY (licence_id) REFERENCES licence(licence_id),
    CONSTRAINT fk_aktivace_verze FOREIGN KEY (verze_konzole) REFERENCES verze_programu(verze),
    CONSTRAINT uq_aktivace_licence_stroj UNIQUE (licence_id, machine_id),
    CONSTRAINT ck_aktivace_poradi CHECK (poradi > 0)
);

-- Karta školy: poznámky a požadavky
CREATE TABLE zakaznik_zaznamy (
    zaznam_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zakaznik_id   INTEGER NOT NULL,
    kdy           DATE NOT NULL DEFAULT CURRENT_DATE,
    druh          VARCHAR(10) NOT NULL DEFAULT 'poznamka',
    text          TEXT NOT NULL,
    vyreseno      DATE,
    CONSTRAINT fk_zaznamy_zakaznik FOREIGN KEY (zakaznik_id) REFERENCES zakaznici(zakaznik_id),
    CONSTRAINT ck_zaznamy_druh CHECK (druh IN ('poznamka', 'pozadavek')),
    CONSTRAINT ck_zaznamy_vyreseno CHECK (vyreseno IS NULL OR druh = 'pozadavek')
);

-- Faktury (číslo faktury je zároveň variabilní symbol)
CREATE TABLE faktury (
    faktura_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cislo         CHAR(8) NOT NULL UNIQUE,
    zakaznik_id   INTEGER,
    odb_nazev     VARCHAR(200) NOT NULL,
    odb_ico       CHAR(8),
    popis         VARCHAR(200) NOT NULL,
    vystaveno     DATE NOT NULL,
    splatnost     DATE NOT NULL,
    celkem        INTEGER NOT NULL,
    stav          VARCHAR(10) NOT NULL DEFAULT 'vystavena',
    zaplaceno     DATE,
    stornovano    DATE,
    CONSTRAINT fk_faktury_zakaznik FOREIGN KEY (zakaznik_id) REFERENCES zakaznici(zakaznik_id) ON DELETE SET NULL,
    CONSTRAINT ck_faktury_stav CHECK (stav IN ('vystavena', 'zaplacena', 'stornovana')),
    CONSTRAINT ck_faktury_celkem CHECK (celkem > 0),
    CONSTRAINT ck_faktury_splatnost CHECK (splatnost >= vystaveno),
    CONSTRAINT ck_faktury_zaplaceno CHECK (stav <> 'zaplacena' OR zaplaceno IS NOT NULL)
);

-- Předpisy plateb za licence (vazební tabulka mezi licence a faktury)
CREATE TABLE platby (
    platba_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    licence_id    INTEGER NOT NULL,
    faktura_id    INTEGER,
    vznik         DATE NOT NULL DEFAULT CURRENT_DATE,
    duvod         VARCHAR(12) NOT NULL DEFAULT 'rucne',
    plati_do      DATE,
    castka        INTEGER NOT NULL,
    stav          VARCHAR(12) NOT NULL DEFAULT 'ceka',
    zaplaceno     DATE,
    CONSTRAINT fk_platby_licence FOREIGN KEY (licence_id) REFERENCES licence(licence_id),
    CONSTRAINT fk_platby_faktura FOREIGN KEY (faktura_id) REFERENCES faktury(faktura_id) ON DELETE SET NULL,
    CONSTRAINT ck_platby_duvod CHECK (duvod IN ('zalozeni', 'prodlouzeni', 'rucne')),
    CONSTRAINT ck_platby_stav CHECK (stav IN ('ceka', 'zaplaceno', 'neuctuje_se')),
    CONSTRAINT ck_platby_castka CHECK (castka >= 0)
);

-- Pohyby (příchozí platby stažené z banky, klíčem je ID pohybu z banky)
CREATE TABLE pohyby (
    pohyb_id          BIGINT PRIMARY KEY,
    datum             DATE NOT NULL,
    castka            NUMERIC(12, 2) NOT NULL,
    vs                VARCHAR(10),
    protiucet         VARCHAR(40),
    kod_banky         VARCHAR(4),
    nazev_protiuctu   VARCHAR(120),
    stav              VARCHAR(10) NOT NULL DEFAULT 'nove',
    faktura_id        INTEGER,
    sparovano         DATE,
    samo              BOOLEAN,
    CONSTRAINT fk_pohyby_faktura FOREIGN KEY (faktura_id) REFERENCES faktury(faktura_id),
    CONSTRAINT ck_pohyby_castka CHECK (castka > 0),
    CONSTRAINT ck_pohyby_stav CHECK (stav IN ('nove', 'sparovano', 'nepatri')),
    CONSTRAINT ck_pohyby_sparovano CHECK (stav <> 'sparovano' OR faktura_id IS NOT NULL)
);


-- Indexy na cizí klíče, přes které se nejčastěji spojuje
CREATE INDEX idx_licence_zakaznik ON licence(zakaznik_id);
CREATE INDEX idx_aktivace_licence ON aktivace(licence_id);
CREATE INDEX idx_zaznamy_zakaznik ON zakaznik_zaznamy(zakaznik_id);
CREATE INDEX idx_faktury_zakaznik ON faktury(zakaznik_id);
CREATE INDEX idx_platby_licence ON platby(licence_id);
CREATE INDEX idx_platby_faktura ON platby(faktura_id);
CREATE INDEX idx_pohyby_faktura ON pohyby(faktura_id);
