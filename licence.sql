-- Evidence licencí a plateb softwaru pro školy
-- Vytvoří schéma licence a jeho 8 tabulek.
-- POZOR: skript na začátku smaže celé schéma licence i s daty.

DROP SCHEMA IF EXISTS licence CASCADE;
CREATE SCHEMA IF NOT EXISTS licence;

-- Zákazník = škola. Kontaktní osoba je přímo na škole.
CREATE TABLE licence.zakaznici (
    zakaznik_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazev varchar(200) NOT NULL,
    ico char(8) UNIQUE,
    adresa varchar(200),
    email varchar(150) NOT NULL,
    kontakt varchar(100),
    telefon varchar(20),
    stav varchar(10) NOT NULL DEFAULT 'zajemce',
    ozvat_se date,
    vytvoreno timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT zakaznici_stav_znamy CHECK (stav IN ('zajemce', 'zkousi', 'plati', 'odesla')),
    CONSTRAINT zakaznici_ico_tvar CHECK (ico IS NULL OR ico ~ '^[0-9]{8}$')
);

-- Licence = jedna instalace programu, identifikovaná licenčním kódem.
CREATE TABLE licence.licence (
    licence_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zakaznik_id integer NOT NULL REFERENCES licence.zakaznici (zakaznik_id),
    kod char(19) NOT NULL UNIQUE,
    popisek varchar(100),
    edice varchar(10) NOT NULL DEFAULT 'pro',
    max_stanic integer NOT NULL DEFAULT 30,
    plati_do date NOT NULL,
    zruseno boolean NOT NULL DEFAULT false,
    archivovano timestamptz,
    vytvoreno timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT licence_kod_tvar
        CHECK (kod ~ '^RSTR(-[ABCDEFGHJKMNPQRSTUVWXYZ23456789]{4}){3}$'),
    CONSTRAINT licence_edice_znama CHECK (edice IN ('pro', 'basic', 'trial')),
    CONSTRAINT licence_max_stanic_v_mezich CHECK (max_stanic BETWEEN 1 AND 1000)
);

-- Vydané verze programu. Přirozený primární klíč = číslo verze.
CREATE TABLE licence.verze_programu (
    verze varchar(11) PRIMARY KEY,
    odkaz varchar(500) NOT NULL,
    poznamky text,
    vydano timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT verze_programu_tvar CHECK (verze ~ '^[0-9]{1,3}\.[0-9]\.[0-9]$'),
    CONSTRAINT verze_programu_odkaz_https CHECK (odkaz ~ '^https://[^[:space:]]+$')
);

-- Aktivace = počítač, na kterém je licence aktivovaná, a co naposledy hlásil.
CREATE TABLE licence.aktivace (
    aktivace_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    licence_id integer NOT NULL REFERENCES licence.licence (licence_id),
    machine_id char(32) NOT NULL,
    poradi integer NOT NULL,
    prvni_vydani timestamptz NOT NULL DEFAULT now(),
    posledni timestamptz NOT NULL DEFAULT now(),
    vyrazeno timestamptz,
    hlaseno timestamptz,
    verze_konzole varchar(11) REFERENCES licence.verze_programu (verze),
    hlasenych_stanic integer,
    CONSTRAINT aktivace_licence_stroj_unique UNIQUE (licence_id, machine_id),
    CONSTRAINT aktivace_stroj_tvar CHECK (machine_id ~ '^[0-9a-f]{32}$'),
    CONSTRAINT aktivace_poradi_kladne CHECK (poradi > 0),
    CONSTRAINT aktivace_stanic_v_mezich
        CHECK (hlasenych_stanic IS NULL OR hlasenych_stanic BETWEEN 0 AND 1000)
);

-- Karta školy: poznámky a požadavky. Vyřešit jde jen požadavek.
CREATE TABLE licence.zakaznik_zaznamy (
    zaznam_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zakaznik_id integer NOT NULL REFERENCES licence.zakaznici (zakaznik_id),
    kdy timestamptz NOT NULL DEFAULT now(),
    druh varchar(10) NOT NULL DEFAULT 'poznamka',
    text text NOT NULL,
    vyreseno timestamptz,
    CONSTRAINT zaznamy_druh_znamy CHECK (druh IN ('poznamka', 'pozadavek')),
    CONSTRAINT zaznamy_text_ma_obsah CHECK (char_length(btrim(text)) BETWEEN 1 AND 4000),
    CONSTRAINT zaznamy_vyreseno_jen_pozadavek CHECK (vyreseno IS NULL OR druh = 'pozadavek')
);

-- Faktury. Číslo faktury je zároveň variabilní symbol.
-- Odběratel je zkopírovaný, aby se doklad nezměnil po úpravě nebo smazání školy.
CREATE TABLE licence.faktury (
    faktura_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cislo char(8) NOT NULL UNIQUE,
    zakaznik_id integer REFERENCES licence.zakaznici (zakaznik_id) ON DELETE SET NULL,
    odb_nazev varchar(200) NOT NULL,
    odb_ico char(8),
    popis varchar(200) NOT NULL,
    vystaveno date NOT NULL,
    splatnost date NOT NULL,
    celkem integer NOT NULL,
    stav varchar(10) NOT NULL DEFAULT 'vystavena',
    zaplaceno date,
    stornovano timestamptz,
    CONSTRAINT faktury_cislo_tvar CHECK (cislo ~ '^[0-9]{8}$'),
    CONSTRAINT faktury_stav_znamy CHECK (stav IN ('vystavena', 'zaplacena', 'stornovana')),
    CONSTRAINT faktury_celkem_kladne CHECK (celkem > 0),
    CONSTRAINT faktury_splatnost_po_vystaveni CHECK (splatnost >= vystaveno),
    CONSTRAINT faktury_uhrada_sedi CHECK ((stav = 'zaplacena') = (zaplaceno IS NOT NULL)),
    CONSTRAINT faktury_storno_sedi CHECK ((stav = 'stornovana') = (stornovano IS NOT NULL))
);

-- Předpis platby za licenci a období (vazební tabulka licence ↔ faktury).
CREATE TABLE licence.platby (
    platba_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    licence_id integer NOT NULL REFERENCES licence.licence (licence_id),
    faktura_id integer REFERENCES licence.faktury (faktura_id) ON DELETE SET NULL,
    vznik timestamptz NOT NULL DEFAULT now(),
    duvod varchar(12) NOT NULL DEFAULT 'rucne',
    plati_do date,
    castka integer NOT NULL,
    stav varchar(12) NOT NULL DEFAULT 'ceka',
    zaplaceno date,
    CONSTRAINT platby_duvod_znamy CHECK (duvod IN ('zalozeni', 'prodlouzeni', 'rucne')),
    CONSTRAINT platby_stav_znamy CHECK (stav IN ('ceka', 'zaplaceno', 'neuctuje_se')),
    CONSTRAINT platby_castka_nezaporna CHECK (castka >= 0),
    CONSTRAINT platby_uhrada_sedi CHECK ((stav = 'zaplaceno') = (zaplaceno IS NOT NULL)),
    CONSTRAINT platby_neuctovana_bez_faktury CHECK (faktura_id IS NULL OR stav <> 'neuctuje_se')
);

-- Příchozí transakce stažené z bankovního API. Klíčem je ID pohybu z banky.
CREATE TABLE licence.pohyby (
    pohyb_id bigint PRIMARY KEY,
    stazeno timestamptz NOT NULL DEFAULT now(),
    datum date NOT NULL,
    castka numeric(12, 2) NOT NULL,
    vs varchar(10),
    protiucet varchar(40),
    kod_banky varchar(4),
    nazev_protiuctu varchar(120),
    stav varchar(10) NOT NULL DEFAULT 'nove',
    faktura_id integer REFERENCES licence.faktury (faktura_id),
    sparovano timestamptz,
    samo boolean,
    CONSTRAINT pohyby_castka_kladna CHECK (castka > 0),
    CONSTRAINT pohyby_vs_tvar CHECK (vs IS NULL OR vs ~ '^[0-9]{1,10}$'),
    CONSTRAINT pohyby_stav_znamy CHECK (stav IN ('nove', 'sparovano', 'nepatri')),
    CONSTRAINT pohyby_sparovani_sedi CHECK (
            (stav = 'sparovano') = (faktura_id IS NOT NULL)
        AND (stav = 'sparovano') = (sparovano IS NOT NULL)
        AND (stav = 'sparovano') = (samo IS NOT NULL))
);

-- Indexy na cizí klíče, přes které se nejčastěji spojuje.
CREATE INDEX licence_zakaznik_id_idx ON licence.licence (zakaznik_id, plati_do);
CREATE INDEX aktivace_licence_id_idx ON licence.aktivace (licence_id);
CREATE INDEX zakaznik_zaznamy_zakaznik_id_idx ON licence.zakaznik_zaznamy (zakaznik_id);
CREATE INDEX faktury_zakaznik_id_idx ON licence.faktury (zakaznik_id);
CREATE INDEX platby_licence_id_idx ON licence.platby (licence_id);
CREATE INDEX platby_faktura_id_idx ON licence.platby (faktura_id);
CREATE INDEX pohyby_faktura_id_idx ON licence.pohyby (faktura_id);
